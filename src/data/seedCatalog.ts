export function createClausesFromStandard(standardCode: string): IsoClauseItem[] {
  const spec = ISO_STANDARDS_CATALOG.find((s) => s.code === standardCode) || ISO_STANDARDS_CATALOG[0];
  return spec.clauses.map((c, idx) => ({
    id: `cl-${idx + 1}`,
    clauseNumber: c.clauseNumber,
    clauseTitle: c.clauseTitle,
    requirementDescription: c.requirementDescription,
    applicability: 'Applicable',
    assessmentQuestion: c.assessmentQuestion,
    expectedEvidence: c.expectedEvidence,
    evidenceNote: '',
    implementationStatus: 'In Progress',
    complianceStatus: 'Not Verified',
    gapDescription: '',
    riskClassification: 'Medium',
    auditorComments: '',
    recommendedAction: '',
    responsiblePerson: '',
    targetDate: '',
    closureStatus: 'Open',
  }));
}

export function calculateIsoScore(clauses: IsoClauseItem[]): number {
  const applicable = clauses.filter((c) => c.applicability === 'Applicable' && c.complianceStatus !== 'Not Applicable');
  if (applicable.length === 0) return 0;
  let points = 0;
  for (const c of applicable) {
    if (c.complianceStatus === 'Compliant') points += 100;
    else if (c.complianceStatus === 'Partially Compliant') points += 50;
  }
  return Math.round(points / applicable.length);
}

export function calculateAuditScore(items: AuditChecklistItem[]): number {
  const applicable = items.filter((i) => i.response !== 'N/A' && i.response !== 'Pending');
  if (applicable.length === 0) return 0;
  let points = 0;
  for (const item of applicable) {
    if (item.response === 'Compliant') points += 100;
    else if (item.response === 'Partial') points += 50;
  }
  return Math.round(points / applicable.length);
}

